"""Opcode/operand definitions for the RAPNTWN ADB VM. See vm_analysis.md."""

from dataclasses import dataclass


ARITHMETIC = {ord(c): name for c, name in zip("$*+-./=|", (
    "AND", "MUL", "ADD", "SUB_CLAMP", "MOD", "DIV", "SET", "OR",
))}
CONDITIONS = {ord(c): name for c, name in zip("={}~", (
    "EQ", "LE", "GE", "NE",
))}
SUBCODES = {"a": ARITHMETIC, "c": CONDITIONS}
WIDTHS = dict(w=2, d=4, b=1, p=4, g=4, v=2, a=1, c=1, j=0)
STRINGS = frozenset("sre")
BUFFER_SIZE = 0x100000


@dataclass(frozen=True)
class Opcode:
    code: int
    mnemonic: str
    operands: str
    supported: bool = True

    @property
    def bytecode(self) -> bytes:
        return self.code.to_bytes(2, "little")

    @property
    def minimum_length(self) -> int:
        return 2 + sum(WIDTHS.get(t, 1) for t in self.operands)

    @property
    def sub_opcodes(self) -> dict[int, str]:
        return next((SUBCODES[t] for t in self.operands if t in SUBCODES), {})


